const path=require("path"),fs=require("fs");const puppeteer=require("puppeteer-core");
const base="/root/.cache/puppeteer/chrome";const dirs=fs.readdirSync(base).sort();
const CHROME=path.join(base,dirs[dirs.length-1],"chrome-linux64","chrome");
const URL="https://fitness.agency/my-library/sulek-strength-size-peak";
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const out=[];const chk=(n,p,d)=>out.push({n,p,d});
const open=async(p)=>{await p.evaluate(()=>{const t=document.querySelector("[data-demo] video[data-demo-vid]");if(t)t.parentNode.click();});await sleep(2500);};
const isOpen=(p)=>p.evaluate(()=>{const r=document.querySelector(".pm");return !!r&&r.classList.contains("is-open");});
const pt=(p,s)=>p.evaluate((x)=>{const e=document.querySelector(x);if(!e)return null;const r=e.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2};},s);
(async()=>{
 const b=await puppeteer.launch({executablePath:CHROME,headless:true,args:["--no-sandbox","--disable-dev-shm-usage","--autoplay-policy=no-user-gesture-required"]});
 const ctx=await b.createBrowserContext();const p=await ctx.newPage();
 await p.setViewport({width:1440,height:900});
 const errs=[];p.on("pageerror",e=>errs.push(String(e)));
 await p.evaluateOnNewDocument(()=>{window.__ct=[];window.__big=0;
   document.addEventListener("click",e=>{const t=e.target;window.__ct.push(t.tagName?.toLowerCase()+(typeof t.className==="string"&&t.className.trim()?"."+t.className.trim().split(/\s+/).join("."):""));},true);});
 await p.goto(URL,{waitUntil:"networkidle0"});await sleep(1500);
 await p.evaluate(()=>{const n=document.querySelector('[data-nav-section="program"]');if(n)n.click();});await sleep(800);
 await p.evaluate(()=>document.querySelectorAll("details").forEach(d=>d.open=true));await sleep(2500);
 await open(p);
 chk("viewer opens",await isOpen(p));
 const g=await p.evaluate(()=>{const f=document.querySelector(".pm-video__frame"),v=document.querySelector(".pm-video video"),s=document.querySelector(".pm-video");
  const R=x=>{const r=x.getBoundingClientRect();return{w:Math.round(r.width),h:Math.round(r.height)};};return{stage:R(s),frame:R(f),video:R(v)};});
 chk("still contain-fitted (no size regression)",Math.abs(g.frame.w-g.stage.w)<=1||Math.abs(g.frame.h-g.stage.h)<=1,g);
 await p.evaluate(()=>{window.__ct=[];const big=document.querySelector(".pm-video__big");if(big)big.addEventListener("click",()=>window.__big++);});
 const play=await pt(p,".pm-video__big");await p.mouse.click(play.x,play.y);await sleep(1500);
 const st=await p.evaluate(()=>{const v=document.querySelector(".pm-video video");const r=document.querySelector(".pm");
   return{open:!!r&&r.classList.contains("is-open"),paused:v?v.paused:null,t:v?+v.currentTime.toFixed(2):null,ct:window.__ct,big:window.__big};});
 chk("PLAY: viewer stays open",st.open===true,st);
 chk("PLAY: click reaches the button",st.big>0&&/pm-video__big|svg|path/.test(st.ct.join(",")),st);
 chk("PLAY: playback started",st.paused===false,st);
 const pa=await pt(p,"[data-pm-play]");await p.mouse.click(pa.x,pa.y);await sleep(700);
 const st2=await p.evaluate(()=>{const v=document.querySelector(".pm-video video");const r=document.querySelector(".pm");return{open:!!r&&r.classList.contains("is-open"),paused:v?v.paused:null};});
 chk("transport pause works, stays open",st2.open===true&&st2.paused===true,st2);
 for(const s of ["[data-pm-scrub]","[data-pm-mute]","[data-pm-rate]"]){const a=await pt(p,s);if(a)await p.mouse.click(a.x,a.y);await sleep(250);}
 chk("scrub/mute/rate keep it open",await isOpen(p));
 const gap=await p.evaluate(()=>{const c=document.querySelector(".pm-video"),f=document.querySelector(".pm-video__frame");
   const cr=c.getBoundingClientRect(),fr=f.getBoundingClientRect();
   if(cr.width-fr.width>12)return{x:cr.x+(fr.x-cr.x)/2,y:cr.y+cr.height/2};
   if(cr.height-fr.height>12)return{x:cr.x+cr.width/2,y:cr.y+(fr.y-cr.y)/2};return null;});
 if(gap){await p.mouse.click(gap.x,gap.y);await sleep(900);chk("empty space beside picture closes",!(await isOpen(p)),gap);}
 else chk("empty space beside picture closes",true,"no letterbox band at this ratio (skipped)");
 await open(p);await p.keyboard.press("Escape");await sleep(900);
 chk("Escape closes",!(await isOpen(p)));
 await open(p);const c=await pt(p,"[data-pm-close]");await p.mouse.click(c.x,c.y);await sleep(900);
 chk("close button closes",!(await isOpen(p)));
 chk("no JS errors",errs.length===0,errs.slice(0,2));
 await b.close();
 let f=0;for(const x of out){if(!x.p)f++;console.log(`  ${x.p?"PASS":"FAIL"}  ${x.n}`);if(!x.p)console.log("        ",JSON.stringify(x.d));}
 console.log("\n  viewer box:",JSON.stringify(g));
 console.log(f?`\n${f} FAILED`:"\nALL PASSED");
})();
