// The <head> tags every server-rendered page shares: the icon links, and the
// OpenGraph/Twitter block that link previews (WhatsApp, Facebook, iMessage,
// Slack, X) and Google read.
//
// One builder on purpose. Until 2026-11 there were six hand-written copies in
// routes/pages.js, and they had drifted: some sent `summary` cards, the shop
// sent no og:image at all, none sent og:image dimensions or alt, and the
// image they did send was a theme placeholder (a grey 1920x341 PNG with its
// own size printed on it, served under a .jpg name). Crawlers do not run JS,
// so whatever this returns is the whole preview.
//
// The icon files themselves are generated by tools/build-icons.js; the
// static .html templates carry the same icon block hardcoded, because the
// admin pages are served by express.static and never pass through here.
const fs = require("fs");
const path = require("path");
const { coverMedia, normalizeImageUrl } = require("./media");

const SITE_NAME = "Fitness Agency";
const SITE_ROOT = path.join(__dirname, "..", "..", "..");

// og:url and og:image must be absolute, or a crawler drops them. APP_URL is
// set in production; the fallback only keeps a misconfigured environment
// from emitting relative URLs that every preview would silently ignore.
function siteUrl(pathname) {
  const base = (process.env.APP_URL || "https://fitness.agency").replace(/\/+$/, "");
  return base + pathname;
}

function absolute(url) {
  return /^https?:\/\//.test(url) ? url : siteUrl(url.startsWith("/") ? url : "/" + url);
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

const ICON_LINKS = [
  '<link rel="icon" href="/favicon.ico" sizes="48x48">',
  '<link rel="icon" href="/icon.svg" type="image/svg+xml" data-brand-favicon>',
  '<link rel="icon" href="/icon-192.png" type="image/png" sizes="192x192">',
  '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
];

const DEFAULT_OG_IMAGE = {
  url: "/og/default.jpg",
  width: 1200,
  height: 630,
  type: "image/jpeg",
  alt: "Fitness Agency: workout and meal plans from pro athletes",
};

// What every preview consumer can actually display. SVG is rejected by all
// of them, AVIF by most, so a product whose cover is an SVG gets the default
// card rather than no image at all.
const RASTER_TYPES = { jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", webp: "image/webp", gif: "image/gif" };

// A page's own image (product cover, partner avatar) as an og:image, or null
// when there is nothing a crawler could use, in which case the caller falls
// back to DEFAULT_OG_IMAGE. Width/height come from the media pipeline's
// manifest and are omitted when unknown rather than guessed: a wrong size is
// worse than none, because crawlers trust it for layout.
function pageImage(storedUrl, alt) {
  if (!storedUrl) return null;
  const url = normalizeImageUrl(storedUrl);
  const ext = (url.split(/[?#]/)[0].match(/\.([a-z0-9]+)$/i) || [])[1];
  const type = ext && RASTER_TYPES[ext.toLowerCase()];
  if (!type) return null;

  if (!/^https?:\/\//.test(url)) {
    // A stored path whose file is gone would hand every crawler a 404.
    const abs = path.resolve(SITE_ROOT, url.replace(/^\/+/, "").split(/[?#]/)[0]);
    if (!abs.startsWith(SITE_ROOT + path.sep) || !fs.existsSync(abs)) return null;
  }

  const media = coverMedia(url);
  return {
    url,
    width: media && media.width,
    height: media && media.height,
    type,
    alt,
  };
}

// The OpenGraph + Twitter block. Takes RAW strings and escapes them itself,
// so callers never have to track which of their values are already escaped.
// Returns lines joined with the indentation the templates use around their
// SEO markers.
function socialMeta({ type = "website", title, description, url, image }) {
  const img = image || DEFAULT_OG_IMAGE;
  const imgUrl = esc(absolute(img.url));
  const lines = [
    `<meta property="og:type" content="${esc(type)}">`,
    `<meta property="og:site_name" content="${SITE_NAME}">`,
    url ? `<meta property="og:url" content="${esc(absolute(url))}">` : null,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(description)}">`,
    `<meta property="og:image" content="${imgUrl}">`,
    `<meta property="og:image:secure_url" content="${imgUrl}">`,
    img.width ? `<meta property="og:image:width" content="${img.width}">` : null,
    img.height ? `<meta property="og:image:height" content="${img.height}">` : null,
    `<meta property="og:image:type" content="${esc(img.type)}">`,
    `<meta property="og:image:alt" content="${esc(img.alt || title)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(title)}">`,
    `<meta name="twitter:description" content="${esc(description)}">`,
    `<meta name="twitter:image" content="${imgUrl}">`,
  ];
  return lines.filter(Boolean).join("\n    ");
}

module.exports = { ICON_LINKS, DEFAULT_OG_IMAGE, pageImage, socialMeta };
